"""Rebuild landing portraits with Pillow (python -m pip install Pillow)."""
import base64
import io
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "static" / "landing"
OUTPUT.mkdir(exist_ok=True)
LIBRARY_PORTRAITS = {
    "Hemingway", "Lovecraft", "Hesse", "Rilke", "Baudelaire", "Mistral",
    "Lispector", "Carpentier", "Fuentes", "Castellanos", "Storni", "Asturias",
}
names = sorted(set(re.findall(
    r"static/imgs/([^']+)\.png", (ROOT / "index.js").read_text()
)))
previews = {}
for name in names:
    with Image.open(ROOT / "static" / "imgs" / f"{name}.png") as original:
        # Encode the displayed grayscale treatment once, offline.
        portrait = original.convert("RGB").convert("L").convert("RGB")
        for size, quality in [(480, 64), (960, 76)]:
            resized = portrait.copy()
            resized.thumbnail((size, size), Image.Resampling.LANCZOS)
            resized.save(
                OUTPUT / f"{name}-{size}.webp", quality=quality, method=6
            )
        if name in LIBRARY_PORTRAITS:
            # Readers, maps and the oracle use the same compressed portrait.
            (ROOT / "static" / "imgs" / f"{name}.webp").write_bytes(
                (OUTPUT / f"{name}-960.webp").read_bytes()
            )
        portrait.thumbnail((32, 32), Image.Resampling.LANCZOS)
        buffer = io.BytesIO()
        portrait.save(buffer, format="WEBP", quality=30, method=6)
        previews[name] = "data:image/webp;base64," + base64.b64encode(
            buffer.getvalue()
        ).decode()

# Inline previews appear before image requests finish, even on tab changes.
script = (
    "/* Generated by tools/optimize_landing_images.py */\n"
    "window.coemPortraitPreviews = "
    + json.dumps(previews, separators=(",", ":")) + ";\n"
)
(OUTPUT / "previews.js").write_text(script)
html_path = ROOT / "index.html"
html = html_path.read_text()
for name in ["Pizarnik", "quiroga", "Borges"]:
    html = re.sub(
        r'(data-preview="' + name + r'" src=")[^"]+',
        lambda match: match[1] + previews[name], html
    )
html = re.sub(
    r'<figure class="route-portrait"[^>]*>',
    '<figure class="route-portrait" style="background-image: url('
    + previews["quiroga"] + ')">', html
)
html_path.write_text(html)
asset_bytes = sum(asset.stat().st_size for asset in OUTPUT.glob("*.webp"))
print(
    f"Built {len(names)} portraits; responsive assets: {asset_bytes:,} bytes"
)
